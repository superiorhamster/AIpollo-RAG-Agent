#!/usr/bin/env bash
set -euo pipefail
umask 077

env_file=${1:-.env}
template=${2:-.env.example}
if [[ ! -f "$env_file" ]]; then
  cp "$template" "$env_file"
fi

for key in AUTH_DB_PASSWORD AUTH_MIGRATION_PASSWORD WORKSPACE_DB_PASSWORD WORKSPACE_MIGRATION_PASSWORD AUTH_WORKSPACE_TOKEN AUTH_JWT_SIGNING_KEY DOCUMENT_DB_PASSWORD DOCUMENT_MIGRATION_PASSWORD INGESTION_DB_PASSWORD INGESTION_MIGRATION_PASSWORD WORKSPACE_DOCUMENT_TOKEN DOCUMENT_INGESTION_TOKEN DOCUMENT_STORAGE_PASSWORD WORKSPACE_BROKER_PASSWORD DOCUMENT_BROKER_PASSWORD INGESTION_BROKER_PASSWORD MODEL_EMBEDDING_TOKEN INGESTION_RETRIEVAL_TOKEN ORCHESTRATION_DB_PASSWORD ORCHESTRATION_MIGRATION_PASSWORD WORKSPACE_INTERACTION_TOKEN RETRIEVAL_INTERACTION_TOKEN DOCUMENT_RETRIEVAL_TOKEN MODEL_CHAT_TOKEN ARTIFACT_DB_PASSWORD ARTIFACT_MIGRATION_PASSWORD ORCHESTRATION_ARTIFACT_TOKEN ADMIN_DOMAIN_TOKEN; do
  if ! grep -Eq "^([[:space:]]*export[[:space:]]+)?${key}[[:space:]]*=[[:space:]]*[^[:space:]#]" "$env_file"; then
    value="$(od -An -N32 -tx1 /dev/urandom | tr -d '[:space:]')"
    printf '\n%s=%s\n' "$key" "$value" >> "$env_file"
  fi
done

chmod u=rw,go= "$env_file"
