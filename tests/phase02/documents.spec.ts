import { expect, test } from '@playwright/test'

test('uploads PDF and DOCX, navigates pages, downloads the original, and deletes the workspace', async ({ page }) => {
  test.slow()
  const email = `documents-web-${Date.now()}@example.com`
  await page.goto('/register')
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password', { exact: true }).fill('Phase2!a')
  await page.getByLabel('Confirm password', { exact: true }).fill('Phase2!a')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page).toHaveURL(/\/sign-in\?registered=1$/)
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password', { exact: true }).fill('Phase2!a')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('textbox', { name: 'Workspace name' }).fill('Research sources')
  await page.getByRole('button', { name: 'Create workspace' }).click()
  await page.getByRole('article', { name: 'Research sources' }).getByRole('link', { name: 'Documents' }).click()

  await page.getByLabel('Document file').setInputFiles('/fixtures/study.pdf')
  await page.getByRole('button', { name: 'Upload document' }).click()
  await expect(page.getByRole('img', { name: 'PDF page 1' })).toHaveAttribute('data-rendered', 'true', {timeout:30000})
  await expect(page.getByText('Page 1 of 2')).toBeVisible()
  await page.getByRole('button', { name: 'Next page' }).click()
  await expect(page.getByText('Page 2 of 2')).toBeVisible()
  await expect(page).toHaveURL(/page=2/)
  await page.reload()
  await expect(page.getByText('Page 2 of 2')).toBeVisible({ timeout: 12000 })
  await page.getByRole('button', { name: 'Find in PDF', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Text to find' }).fill('Academic source reference')
  await page.getByRole('button', { name: 'Find next', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Match on page 2' })).toBeVisible()
  await page.getByRole('button', { name: 'Find in PDF', exact: true }).click()

  const notes = page.getByRole('region', { name: 'Personal annotations' })
  await notes.getByRole('button', { name: 'Add note' }).click()
  await notes.getByLabel('Personal note').fill('Synthetic page two note')
  await notes.getByRole('button', { name: 'Save note', exact: true }).click()
  await expect(notes.getByText('Synthetic page two note')).toBeVisible()
  await notes.getByRole('button', { name: 'Annotation actions', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Edit annotation', exact: true }).click()
  await notes.getByLabel('Personal note').fill('Edited synthetic page two note')
  await notes.getByRole('button', { name: 'Save changes', exact: true }).click()
  await page.reload()
  await expect(notes.getByText('p. 2 · 1 item')).toBeVisible({ timeout: 15000 })
  await notes.getByRole('button', { name: 'Expand notes', exact: true }).click()
  await expect(notes.getByText('Edited synthetic page two note')).toBeVisible({timeout:15000})
  await notes.getByRole('button', { name: 'Annotation actions', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Remove annotation', exact: true }).click()
  await notes.getByRole('button', { name: 'Confirm delete', exact: true }).click()
  await expect(notes.getByText('Edited synthetic page two note')).toHaveCount(0)

  // Exercise the real EmbedPDF snapshot against the protected Document API.
  await notes.getByRole('button', { name: 'Select page text' }).click()
  await expect(notes.getByRole('button', { name: 'Highlight text', exact: true })).toBeEnabled()
  const savedHighlight = page.waitForResponse(response => response.url().endsWith('/annotations') && response.request().method() === 'POST')
  await notes.getByRole('button', { name: 'Highlight text', exact: true }).click()
  expect((await savedHighlight).status()).toBe(201)
  await expect(notes.getByRole('listitem')).toHaveCount(1)
  await page.reload()
  await expect(page.getByRole('img', {name:'PDF page 2',exact:true})).toHaveAttribute('data-rendered','true',{timeout:15000})
  await notes.getByRole('button', { name: 'Expand notes', exact: true }).click()
  await expect(notes.getByRole('listitem')).toHaveCount(1)
  await notes.getByRole('button', { name: 'Annotation actions', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Remove annotation', exact: true }).click()
  await notes.getByRole('button', { name: 'Confirm delete', exact: true }).click()
  await expect(notes.getByRole('listitem')).toHaveCount(0)

  await page.getByRole('complementary', { name: 'Workspace navigation' })
    .getByRole('button', { name: 'Documents', exact: true }).click()
  await page.getByLabel('Document file').setInputFiles('/fixtures/paper.docx')
  await page.getByRole('button', { name: 'Upload document' }).click()
  const readerRegion = page.getByRole('region', { name: 'Document preview' })
  await expect(readerRegion.getByRole('button', { name: 'paper.docx', exact: true })).toBeVisible()
  const search = page.getByRole('searchbox', { name: 'Search workspaces and sources' })
  await search.fill('paper.docx')
  await page.getByRole('link', { name: 'paper.docx Source', exact: true }).click()
  await expect(search).toHaveValue('')
  const download = page.waitForEvent('download')
  await readerRegion.getByRole('button', { name: 'Download original', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('paper.docx')
  await expect(page.getByText('Page 1 of 1')).toBeVisible({ timeout: 35000 })

  await page.getByRole('complementary', { name: 'Workspace navigation' })
    .getByRole('button', { name: 'Documents', exact: true }).click()
  const paperRow = page.getByRole('row').filter({ hasText: 'paper.docx' })
  page.once('dialog', dialog => dialog.accept())
  await paperRow.getByRole('button', { name: 'Delete paper.docx' }).click()
  await expect(page.getByRole('row').filter({ hasText: 'paper.docx' })).toHaveCount(0)
  await page.reload()
  await page.getByRole('complementary', { name: 'Workspace navigation' })
    .getByRole('button', { name: 'Documents', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'paper.docx' })).toHaveCount(0)
  await expect(page.getByRole('row').filter({ hasText: 'study.pdf' })).toBeVisible()

  await page.getByRole('link', { name: 'Back to workspaces' }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('article', { name: 'Research sources' }).getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.getByText('You have no workspaces yet.')).toBeVisible()
})
